def requested_known_fact_specs(normalized_question: str) -> list[KnownFactSpec]:
    selected: list[KnownFactSpec] = []
    seen_sentences: set[str] = set()
    for triggers, sentence, required_terms in KNOWN_FACT_CATALOG:
        if sentence in seen_sentences:
            continue
        if all(trigger in normalized_question for trigger in triggers):
            selected.append((sentence, required_terms))
            seen_sentences.add(sentence)
    return selected
