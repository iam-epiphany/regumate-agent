T = []  # rows appended below


def q(id_, question, answerable, qtype, difficulty, relevance, *,
      canonical=None, conclusions=None, aspects=None, sources=None,
      calc=None, refusal_code=None, refusal_rationale=None):
    row = {
        "id": id_, "question": question, "answerable": answerable,
        "question_type": qtype, "difficulty": difficulty,
        "business_relevance": relevance,
        "canonical_answer": canonical, "required_conclusions": conclusions or [],
        "required_evidence_aspects": aspects or [],
        "required_sources": sources or [],
        "calculation": calc,
        "expected_refusal_code": refusal_code, "refusal_rationale": refusal_rationale,
    }
    T.append(row)


def text_src(rel, evidence):
    return {"relative_path": rel, "evidence_text": evidence}


def cell_src(rel, sheet, row, col, coord, expected):
    return {"relative_path": rel, "sheet": sheet, "row": row, "column": col,
            "coordinate": coord, "expected_value": expected}


